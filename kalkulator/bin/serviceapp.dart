class Kalkulator{
  double bilangan1;
  double bilangan2;

  Kalkulator(this.bilangan1, this.bilangan2); 

  double tambah(){
    return bilangan1 + bilangan2;
  }
  
  double kurang(){
    return bilangan1 - bilangan2;
  }

  double kali(){
    return bilangan1 * bilangan2;
  }

  double bagi(){
    return bilangan1 / bilangan2;
  }

}

